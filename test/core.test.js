/** A throwaway copy of a fixture, so tests can write. */
function scratch(name) {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'fcs-'));
  fs.cpSync(path.join(FIX, name), dir, { recursive: true });
  return dir;
}

test('colour: oklch, hex, rgb, alpha', () => {
  assert.equal(cssColorToHex('oklch(1 0 0)'), '#ffffff');
  assert.equal(cssColorToHex('oklch(0 0 0)'), '#000000');
  assert.equal(cssColorToHex('oklch(1 0 0 / 10%)'), '#ffffff1a');
  assert.equal(cssColorToHex('oklch(0.666 0.157 58.318)'), '#d97708'); // amber-600 round-tripped through oklch
  assert.equal(cssColorToHex('#ABC'), '#aabbcc');
  assert.equal(cssColorToHex('#d97706ff'), '#d97706');
  assert.equal(cssColorToHex('rgb(217, 119, 6)'), '#d97706');
  assert.equal(cssColorToHex('var(--x)'), null);
});

test('css-tailwind4: modes, brand override, radii, fonts — and a deterministic file', () => {
  const dir = scratch('web');
  const config = loadConfig(dir);
  const { text, errors } = tokens.build(config);
  assert.deepEqual(errors, []);
  const doc = JSON.parse(text);
  assert.equal(doc.color.primary.$value, '#d97706');
  assert.equal(doc.color.primary.$extensions.modes.dark, '#d97706', 'the later `:root, .dark` block wins in both modes');
  assert.equal(doc.color.background.$extensions.modes.dark, '#000000');
  assert.equal(doc.color.border.$extensions.modes.dark, '#ffffff1a');
  assert.equal(doc.color.primary.$extensions.web.var, 'var(--primary)');
  assert.equal(doc.radius.lg.$value, '8px');
  assert.equal(doc.radius.sm.$value, '4px');
  assert.equal(doc.font.sans.$extensions.figma.family, 'Inter');
  assert.equal(tokens.build(config).text, text);
  // freshness: missing → stale; written → fresh; source edited → stale
  assert.equal(tokens.check(config).fresh, false);
  tokens.write(config);
  assert.equal(tokens.check(config).fresh, true);
  const css = path.join(dir, 'src/theme.css');
  fs.writeFileSync(css, fs.readFileSync(css, 'utf8').replace('#d97706', '#b45309'));
  assert.equal(tokens.check(config).fresh, false);
});


  fs.writeFileSync(cfgPath, fs.readFileSync(cfgPath, 'utf8').replace("figmaFonts: { 'Inter Variable': 'Inter' }", "figmaFonts: { 'Inter Variable': 'Inter' }, spacing: { steps: [1] }"));

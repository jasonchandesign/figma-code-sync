test('check: clean fixture passes; roster and snapshot drift are caught', () => {
  const dir = scratch('web');
  const config = loadConfig(dir);
  tokens.write(config);
  const roster = { Button: { file: 'src/button.jsx', props: { variant: ['default', 'outline'] } } };
  assert.deepEqual(check.run(config, { roster, iconKeys: ['plus'] }).errors, []);

  const r2 = check.run(config, { roster: { Button: { props: { variant: ['default', 'outline', 'ghost'] } } } });
  assert.ok(r2.errors.some((e) => /variant="ghost" exists in code/.test(e)), r2.errors.join('\n'));

  const snap = path.join(dir, 'design/figma-components.json');
  const s = JSON.parse(fs.readFileSync(snap, 'utf8'));
  s.components[0].axes.Variant.push('link');
  s.components.push({ name: 'Icon/minus' });
  fs.writeFileSync(snap, JSON.stringify(s));
  const r3 = check.run(config);
  assert.ok(r3.errors.some((e) => /Variant=link is not mapped/.test(e)), r3.errors.join('\n'));
  assert.ok(r3.errors.some((e) => /Icon\/minus/.test(e)), r3.errors.join('\n'));
});


test('gate: additive vs breaking', () => {
  const base = { axes: { Variant: ['a', 'b'] }, properties: { Label: 'TEXT' }, shape: { pad: [0, 8, 0, 8], hash: 'x' } };
  assert.equal(snapshot.isAdditive(base, { ...base, axes: { Variant: ['a', 'b', 'c'] } }, 'changed'), true);
  assert.equal(snapshot.isAdditive(base, { ...base, axes: { Variant: ['a'] } }, 'changed'), false);
  assert.equal(snapshot.isAdditive(base, { ...base, properties: { Label: 'BOOLEAN' } }, 'changed'), false);
  assert.equal(snapshot.isAdditive(base, { ...base, shape: { pad: [0, 12, 0, 12], hash: 'y' } }, 'changed'), false);
  assert.deepEqual(snapshot.describe(base, { ...base, axes: { Variant: ['a', 'c'] } }), ['axis Variant +c -b']);
});

test('gate: a waiver must name each component, as a whole word', () => {
  const f = path.join(os.tmpdir(), `fcs-msg-${process.pid}`);
  const ack = (msg, names) => {
    fs.writeFileSync(f, msg);
    return snapshot.acknowledgement(os.tmpdir(), names, f).named;
  };
  const quiet = console.error;
  console.error = () => {};
  try {
    assert.deepEqual(ack('x\n\nDesign-drift: Button — padding only', ['Button']), ['Button']);
    assert.deepEqual(ack('how Design-drift: lines work', ['Button']), []);
    assert.deepEqual(ack('Design-drift: IconButton — radius', ['Button']), []);
  } finally {
    console.error = quiet;
    fs.unlinkSync(f);
  }
});

